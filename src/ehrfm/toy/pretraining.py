"""A self-contained toy continued-pretraining run.

:func:`toy_training_config` writes the seeded synthetic extract
(:mod:`ehrfm.toy.artifacts`) and a toy CLMBR checkpoint built from its codes
(:mod:`ehrfm.toy.checkpoint`) into a work directory, then returns a training
configuration over them. Every input is regenerated byte-identically from the
seed, so the run fingerprint, and therefore the cache, is stable across
invocations that share the work directory.
"""

from __future__ import annotations

import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from ehrfm.config.training import (
    OptimizationConfig,
    RuntimeConfig,
    TrainingConfig,
    TrainingInputs,
)
from ehrfm.toy.artifacts import (
    COVARIATES_CSV,
    DATASET_NAME,
    LAB_CODES,
    OBSERVATION_CODES,
    OBSERVATION_TEXTS,
    PARENT_GROUPS,
    TASK_NAME,
    build_artifacts,
)
from ehrfm.toy.checkpoint import CLMBR_VOCAB_SIZE, build_toy_checkpoint

TOY_SUBJECTS: Final = 60
TOY_SEED: Final = 7
TOY_TOKENS_PER_BATCH: Final = 96
TOY_EPOCHS: Final = 3
TOY_LEARNING_RATE: Final = 3e-3


@dataclass(frozen=True, slots=True)
class ToyInputs:
    """Paths of the generated toy inputs."""

    extract: Path
    labels: Path
    checkpoint: Path
    covariates: Path
    """Per-subject ``subject_id,sex,birth_time`` table (see :func:`ehrfm.toy.artifacts.write_covariates`)."""


def write_toy_experiment_inputs(
    work_dir: Path, *, subjects: int = TOY_SUBJECTS, seed: int = TOY_SEED
) -> ToyInputs:
    """(Re)write the toy extract, label set and checkpoint under ``work_dir/inputs``."""
    inputs = work_dir / "inputs"
    shutil.rmtree(inputs, ignore_errors=True)
    artifacts = build_artifacts(inputs / "artifacts", n_subjects=subjects, seed=seed)
    checkpoint = build_toy_checkpoint(
        inputs / "checkpoint",
        extract_codes=artifacts.codes,
        parent_codes=sorted(set(PARENT_GROUPS.values())),
        numeric_properties=LAB_CODES,
        text_properties=[(OBSERVATION_CODES[0], OBSERVATION_TEXTS)],
    )
    return ToyInputs(
        extract=artifacts.extract,
        labels=artifacts.labels,
        checkpoint=checkpoint.path,
        covariates=artifacts.covariates,
    )


def toy_input_paths(work_dir: Path) -> ToyInputs:
    """Where :func:`write_toy_experiment_inputs` puts the inputs under ``work_dir`` (nothing is written)."""
    artifacts = work_dir / "inputs" / "artifacts"
    return ToyInputs(
        extract=artifacts / "meds" / DATASET_NAME,
        labels=artifacts / "labels" / DATASET_NAME / TASK_NAME,
        checkpoint=work_dir / "inputs" / "checkpoint",
        covariates=artifacts / COVARIATES_CSV,
    )


def write_toy_inputs(
    work_dir: Path, *, subjects: int = TOY_SUBJECTS, seed: int = TOY_SEED
) -> tuple[Path, Path]:
    """(Re)write the toy inputs under ``work_dir/inputs``; return the extract and checkpoint."""
    written = write_toy_experiment_inputs(work_dir, subjects=subjects, seed=seed)
    return written.extract, written.checkpoint


def toy_optimization(**overrides: object) -> OptimizationConfig:
    """The toy optimisation settings (18 CPU steps on the default toy extract)."""
    settings: dict[str, object] = {
        "seed": 0,
        "tokens_per_batch": TOY_TOKENS_PER_BATCH,
        "epochs": TOY_EPOCHS,
        "learning_rate": TOY_LEARNING_RATE,
        "warmup_steps": 2,
        "schedule": "cosine",
        "validation_fraction": 0.2,
        "clmbr_vocab_size": CLMBR_VOCAB_SIZE,
    }
    settings.update(overrides)
    return OptimizationConfig.model_validate(settings)


def toy_training_config(
    work_dir: Path,
    *,
    subjects: int = TOY_SUBJECTS,
    seed: int = TOY_SEED,
    optimization: OptimizationConfig | None = None,
    checkpoint_every: int = 5,
) -> TrainingConfig:
    """Write the toy inputs under ``work_dir`` and return a CPU run over them."""
    extract, checkpoint = write_toy_inputs(work_dir, subjects=subjects, seed=seed)
    return TrainingConfig(
        inputs=TrainingInputs(extract=extract, base_checkpoint=checkpoint),
        optimization=optimization or toy_optimization(),
        runtime=RuntimeConfig(
            output_dir=work_dir / "run",
            device="cpu",
            checkpoint_every=checkpoint_every,
            log_every=5,
        ),
    )


__all__ = [
    "ToyInputs",
    "toy_input_paths",
    "toy_optimization",
    "toy_training_config",
    "write_toy_experiment_inputs",
    "write_toy_inputs",
]
